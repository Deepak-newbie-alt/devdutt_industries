
import pdfmake from "pdfmake";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url"
import type { TDocumentDefinitions } from "pdfmake/interfaces.js";

const currentDir = path.dirname(fileURLToPath(import.meta.url));

const fontPath = path.resolve(
    currentDir,
    "../../assets/fonts"
);


const fonts = {
  Roboto: {
    normal: path.join(fontPath, "Roboto-Regular.ttf"),
    bold: path.join(fontPath, "Roboto-Regular.ttf"),
    italics: path.join(fontPath, "Roboto-Italic.ttf"),
    bolditalics: path.join(fontPath, "Roboto-Italic.ttf"),
  },
};

for (const [style, file] of Object.entries(fonts.Roboto)) {
  console.log(style, file);
  console.log("Exists:", fs.existsSync(file));

  if (fs.existsSync(file)) {
    console.log("Size:", fs.statSync(file).size);
    console.log(
      "Signature:",
      fs.readFileSync(file).subarray(0, 4).toString("hex"),
    );
  }
}

pdfmake.addFonts(fonts);

pdfmake.setUrlAccessPolicy(() => false);

const docDefinition: TDocumentDefinitions = {
  content: [
    {
      text: "Devdutt Industries",
      fontSize: 22,
      bold: true,
    },
    {
      text: "My First PDF",
      fontSize: 16,
    },
    "This PDF was generated by my Node.js backend.",
  ],
  defaultStyle: {
    font: "Roboto",
  },
};

async function main() {
  // Verify font files exist before generating the PDF.
  for (const file of Object.values(fonts.Roboto)) {
    if (!fs.existsSync(file)) {
      throw new Error(`Font file not found: ${file}`);
    }
  }

  await pdfmake.createPdf(docDefinition).write("sample.pdf");

  console.log("PDF generated successfully!");
}

main().catch((error: unknown) => {
  console.error("PDF generation failed:", error);
  process.exitCode = 1;
});